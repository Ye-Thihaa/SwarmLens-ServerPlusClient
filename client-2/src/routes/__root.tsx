/** Drains the offline outbox in the background from wherever the guest
 * happens to be in the app -- on a timer, and immediately when the
 * browser regains connectivity. Same "sync from anywhere, never throws"
 * spirit as the Phase 5 reference client's service-worker sync handler,
 * minus the service worker (this app doesn't register one). */
function OutboxSyncDaemon() {
  useEffect(() => {
    void syncOutbox();
    const id = setInterval(() => void syncOutbox(), 4000);
    const onOnline = () => void syncOutbox();
    window.addEventListener("online", onOnline);
    return () => {
      clearInterval(id);
      window.removeEventListener("online", onOnline);
    };
  }, []);
  return null;
}

